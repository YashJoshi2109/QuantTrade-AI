from dataclasses import dataclass, field
from typing import Literal
import re
import logging

logger = logging.getLogger(__name__)

# --- Data types ---

@dataclass
class ComplianceResult:
    action: Literal["allow", "block", "review"]  # review = human queue (Phase 6+)
    stage: int  # 1, 2, or 3
    flags: list[str] = field(default_factory=list)  # matched phrases
    confidence: float | None = None  # FinBERT score (Phase 6+)
    message: str | None = None

# --- Mandatory disclosure template ---
# Must be appended to every agent post before publishing.
AGENT_DISCLOSURE_TEMPLATE = (
    "\n\n---\n"
    "*Generated by {display_name} ({handle}), an AI agent on Quant-Agora. "
    "Not investment advice. [View provenance →](/agora/post/{post_id}/provenance)*"
)

class ComplianceEngine:
    # Stage 1 — advice phrases that always block
    ADVICE_REGEX = re.compile(
        r'\b('
        r'you should buy|you should sell|you should invest|you should divest'
        r'|buy now|sell now|buy immediately|sell immediately'
        r'|strong buy|strong sell|outperform|underperform'
        r'|price target of|price target is'
        r'|guaranteed return|guaranteed profit|guaranteed gain'
        r'|risk.?free return|risk.?free investment'
        r'|sure thing|can\'t lose|can not lose|cannot lose'
        r'|will go up|will go down|will rise|will fall|will rally|will drop'
        r'|definitely buy|definitely sell|definitely invest'
        r'|I recommend buying|I recommend selling|I recommend investing'
        r'|we recommend buying|we recommend selling'
        r')\b',
        re.IGNORECASE
    )

    def stage1_regex(self, text: str) -> ComplianceResult:
        """Regex-based advice phrase detector. Always runs in Phase 3+."""
        matches = self.ADVICE_REGEX.findall(text)
        if matches:
            return ComplianceResult(
                action="block",
                stage=1,
                flags=list(set(m.strip() for m in matches)),
                message=f"Post contains advice phrase(s): {', '.join(set(m.strip() for m in matches))}"
            )
        return ComplianceResult(action="allow", stage=1)

    async def stage2_finbert(self, text: str) -> float:
        """Stage 2 — FinBERT via Cloudflare Workers AI. DEFERRED to Phase 6."""
        raise NotImplementedError("Stage 2 FinBERT deferred to Phase 6")

    async def stage3_llm_review(self, text: str) -> Literal["advice", "analysis", "safe"]:
        """Stage 3 — LLM reviewer for borderline cases. DEFERRED to Phase 6."""
        raise NotImplementedError("Stage 3 LLM review deferred to Phase 6")

    async def classify(self, text: str) -> ComplianceResult:
        """
        Full compliance pipeline.
        Phase 3: Stage 1 only.
        Phase 6: adds Stage 2 (FinBERT) and Stage 3 (LLM reviewer).
        """
        result = self.stage1_regex(text)
        if result.action == "block":
            logger.info("Compliance block (stage 1): flags=%s", result.flags)
            return result
        # Stages 2 and 3 intentionally skipped until Phase 6
        return ComplianceResult(action="allow", stage=1)

    def append_disclosure(self, post_body: str, display_name: str, handle: str, post_id: int | None = None) -> str:
        """Append mandatory AI agent disclosure to post body."""
        disclosure = AGENT_DISCLOSURE_TEMPLATE.format(
            display_name=display_name,
            handle=handle,
            post_id=post_id if post_id is not None else "new"
        )
        return post_body + disclosure


# Module-level singleton
compliance_engine = ComplianceEngine()
