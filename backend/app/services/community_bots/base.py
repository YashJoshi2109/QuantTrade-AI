"""Core types for community bots: the bot spec, the generated post, skips,
formatting helpers and the body / footer renderer.

A bot is two functions:

  collect(hub, now, slot) -> dict      async; reads data through a DataHub
  compose(data, now, slot) -> BotPost  pure and deterministic (raises Skip)

Every number in a post comes from ``data``; wording comes from fixed
templates in the compose function. No LLM is involved.
"""
from __future__ import annotations

import hashlib
import json
import math
from dataclasses import dataclass, field
from datetime import date, datetime, timezone
from typing import Any, Awaitable, Callable, Dict, List, Optional, Sequence, Tuple

from zoneinfo import ZoneInfo

ET = ZoneInfo("America/New_York")

DISCLAIMER = (
    "Not investment advice. Signals and observations are generated by fixed rules "
    "from market data; they are not recommendations to buy or sell any security."
)
# Max characters of any third-party text (headline titles) we show. Titles are
# shown with a link back to the publisher; article text is never copied.
MAX_HEADLINE_CHARS = 140
MAX_LINKS = 5


class Skip(Exception):
    """compose()/collect() decided not to post (stale, missing or thin data)."""

    def __init__(self, reason: str):
        super().__init__(reason)
        self.reason = reason


@dataclass(frozen=True)
class Slot:
    """One scheduled run: local (ET) cron fields + the slot name used in dedupe keys."""
    name: str
    hour: int
    minute: int
    day_of_week: str = "mon-fri"

    def label(self) -> str:
        h12 = self.hour % 12 or 12
        ampm = "AM" if self.hour < 12 else "PM"
        days = {"mon-fri": "weekdays (trading days)", "*": "daily", "mon-sun": "daily"}.get(
            self.day_of_week, self.day_of_week)
        return f"{h12}:{self.minute:02d} {ampm} ET, {days}"


@dataclass
class BotPost:
    title: str
    lead: str
    as_of: datetime
    sources: List[str]
    highlights: List[str] = field(default_factory=list)
    tables: List[Dict[str, Any]] = field(default_factory=list)   # {title, columns, rows}
    chart: Optional[Dict[str, Any]] = None                       # {type: bar, title, unit, series: [{label, value}]}
    badge: Optional[Dict[str, Any]] = None                       # e.g. {kind: weather, value: sunny, label, score}
    links: List[Dict[str, str]] = field(default_factory=list)    # third-party headlines: {title, url, source}
    tickers: List[str] = field(default_factory=list)
    sentiment: Optional[str] = None                              # bullish | bearish | neutral (data tone, not advice)
    notes: List[str] = field(default_factory=list)               # methodology caveats shown under the data

    def content_fingerprint(self) -> str:
        """Hash of the data-bearing content (not the as-of time): identical
        numbers are never posted twice."""
        blob = json.dumps({
            "lead": self.lead, "highlights": self.highlights, "tables": self.tables,
            "chart": self.chart, "badge": self.badge, "links": [l.get("url") for l in self.links],
        }, sort_keys=True, default=str)
        return hashlib.sha256(blob.encode()).hexdigest()


@dataclass(frozen=True)
class BotSpec:
    slug: str
    username: str
    display_name: str
    emoji: str
    tagline: str
    description: str
    methodology: List[str]
    data_sources: List[str]
    community_slug: str
    slots: Tuple[Slot, ...]
    daily_cap: int
    universe: Tuple[str, ...]
    collect: Callable[..., Awaitable[Dict[str, Any]]]
    compose: Callable[..., BotPost]
    trading_days_only: bool = True
    min_interval_minutes: int = 60
    accent: str = "blue"

    def public(self) -> Dict[str, Any]:
        return {
            "slug": self.slug,
            "username": self.username,
            "display_name": self.display_name,
            "emoji": self.emoji,
            "tagline": self.tagline,
            "description": self.description,
            "methodology": list(self.methodology),
            "data_sources": list(self.data_sources),
            "community_slug": self.community_slug,
            "schedule": [{"slot": s.name, "label": s.label()} for s in self.slots],
            "daily_cap": self.daily_cap,
            "universe": list(self.universe),
            "trading_days_only": self.trading_days_only,
            "accent": self.accent,
        }


# ── formatting helpers (deterministic) ───────────────────────────────────────

def finite(v: Any) -> Optional[float]:
    try:
        f = float(v)
    except (TypeError, ValueError):
        return None
    return f if math.isfinite(f) else None


def fmt_pct(v: Optional[float], digits: int = 2, signed: bool = True) -> str:
    if v is None:
        return "n/a"
    s = f"{v:+.{digits}f}%" if signed else f"{v:.{digits}f}%"
    return s.replace("-", "−")


def fmt_pp(v: Optional[float], digits: int = 1) -> str:
    if v is None:
        return "n/a"
    return f"{v:+.{digits}f} pp".replace("-", "−")


def fmt_num(v: Optional[float], digits: int = 2) -> str:
    if v is None:
        return "n/a"
    return f"{v:,.{digits}f}"


def fmt_money(v: Optional[float], digits: int = 2) -> str:
    if v is None:
        return "n/a"
    sign = "−" if v < 0 else ""
    return f"{sign}${abs(v):,.{digits}f}"


def fmt_cap(v: Optional[float]) -> str:
    if v is None:
        return "n/a"
    for div, unit in ((1e12, "T"), (1e9, "B"), (1e6, "M")):
        if abs(v) >= div:
            return f"${v / div:.1f}{unit}"
    return f"${v:,.0f}"


def to_et(dt: datetime) -> datetime:
    if dt.tzinfo is None:
        dt = dt.replace(tzinfo=timezone.utc)
    return dt.astimezone(ET)


def fmt_et(dt: datetime) -> str:
    """'Nov 27, 2026 4:20 PM ET' (no leading zero on the hour, portable)."""
    e = to_et(dt)
    h12 = e.hour % 12 or 12
    return f"{e.strftime('%b')} {e.day}, {e.year} {h12}:{e.minute:02d} {'AM' if e.hour < 12 else 'PM'} ET"


def fmt_day(d: date) -> str:
    return f"{d.strftime('%a %b')} {d.day}"


def et_date(dt: datetime) -> date:
    return to_et(dt).date()


def clip_title(text: str, limit: int = MAX_HEADLINE_CHARS) -> str:
    """Third-party headline -> at most ``limit`` characters on one line."""
    t = " ".join(str(text or "").split())
    if len(t) <= limit:
        return t
    cut = t[: limit - 1].rsplit(" ", 1)[0].rstrip(",;:-")
    return cut + "…"


def age_hours(ts: Optional[datetime], now: datetime) -> Optional[float]:
    if ts is None:
        return None
    if ts.tzinfo is None:
        ts = ts.replace(tzinfo=timezone.utc)
    return (now - ts).total_seconds() / 3600.0


def require_fresh(ts: Optional[datetime], now: datetime, max_hours: float, what: str) -> None:
    age = age_hours(ts, now)
    if age is None:
        raise Skip(f"{what}: no timestamp")
    if age > max_hours:
        raise Skip(f"{what} is stale ({age:.1f}h old, limit {max_hours:g}h)")


def session_as_of(fetched: Optional[datetime], session: date, now: datetime) -> datetime:
    """As-of time of quote data for ``session``: the fetch time, but never later
    than that session's close (a quote fetched at 3:44 PM after a 1:00 PM early
    close is the 1:00 PM close) and never in the future."""
    from app.services import market_calendar as mc
    close = datetime.combine(session, mc.close_time(session), tzinfo=ET)
    ts = fetched or now
    if ts.tzinfo is None:
        ts = ts.replace(tzinfo=timezone.utc)
    return min(ts, close, now)


def fmt_points(n: int) -> str:
    return f"{n:+d}".replace("-", "−")


def bar_chart(title: str, series: Sequence[Tuple[str, Optional[float]]], unit: str = "%") -> Optional[Dict[str, Any]]:
    pts = [{"label": l, "value": round(v, 2)} for l, v in series if v is not None]
    if len(pts) < 2:
        return None
    return {"type": "bar", "title": title, "unit": unit, "series": pts}


# ── body rendering ───────────────────────────────────────────────────────────

def footer_lines(spec: BotSpec, post: BotPost) -> List[str]:
    return [
        f"\U0001F916 Automated post by {spec.display_name} · bot account, not a person",
        f"Sources: {'; '.join(post.sources)}",
        f"As of: {fmt_et(post.as_of)}",
        DISCLAIMER,
    ]


def _table_text(t: Dict[str, Any]) -> List[str]:
    out = [f"**{t['title']}**"] if t.get("title") else []
    cols = t.get("columns") or []
    out.append(" | ".join(str(c) for c in cols))
    for row in t.get("rows") or []:
        out.append(" | ".join(str(c) for c in row))
    return out


def render_body(spec: BotSpec, post: BotPost) -> str:
    """Plain-text/markdown body. It is what every surface that does not know
    about bots (search, profiles, notifications, crawlers) shows, so the
    automated-post labels are part of it, not only of the UI badge."""
    lines: List[str] = [post.lead, ""]
    for h in post.highlights:
        lines.append(f"• {h}")
    if post.highlights:
        lines.append("")
    for t in post.tables:
        lines.extend(_table_text(t))
        lines.append("")
    if post.links:
        lines.append("**Headlines (title + link to the publisher)**")
        for l in post.links:
            lines.append(f"• {l['title']} — {l.get('source') or 'source'}: {l['url']}")
        lines.append("")
    for n in post.notes:
        lines.append(f"_{n}_")
    if post.notes:
        lines.append("")
    lines.append("---")
    lines.extend(footer_lines(spec, post))
    return "\n".join(lines).strip()


def payload_of(spec: BotSpec, post: BotPost, slot: str) -> Dict[str, Any]:
    """Structured payload stored in community_bot_posts and sent to the UI."""
    return {
        "version": 1,
        "bot": {"slug": spec.slug, "display_name": spec.display_name, "emoji": spec.emoji,
                "accent": spec.accent},
        "slot": slot,
        "lead": post.lead,
        "highlights": post.highlights,
        "tables": post.tables,
        "chart": post.chart,
        "badge": post.badge,
        "links": post.links,
        "notes": post.notes,
        "sources": post.sources,
        "as_of": to_et(post.as_of).isoformat(),
        "as_of_label": fmt_et(post.as_of),
        "automated_label": f"Automated post by {spec.display_name}",
        "disclaimer": DISCLAIMER,
    }
