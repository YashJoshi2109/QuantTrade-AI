import { afterEach, describe, expect, it, vi } from 'vitest'
import { cleanup, render, screen } from '@testing-library/react'
import type { AnchorHTMLAttributes, ReactNode } from 'react'

vi.mock('next/link', () => ({
  default: ({ href, children, ...rest }: AnchorHTMLAttributes<HTMLAnchorElement> & { href: string; children: ReactNode }) => (
    <a href={href} {...rest}>{children}</a>
  ),
}))

import BotPostBlock from './BotPostBlock'
import ShowBotsToggle from './ShowBotsToggle'
import type { BotPayload } from '@/lib/communityBots'

const payload: BotPayload = {
  version: 1,
  bot: { slug: 'market_weather', display_name: 'Market Weather Bot', emoji: '⛅', accent: 'amber' },
  slot: 'close',
  lead: 'Sunny (score +5) for today’s session.',
  highlights: ['Breadth: 65% rose.', 'VIX 15.20.', 'SPY 602.50.', 'QQQ +1.20%.'],
  tables: [
    { title: 'How the weather is scored', columns: ['Input', 'Reading', 'Points'],
      rows: [['Breadth', '65%', '+2'], ['VIX', '15.2', '+1'], ['Trend', 'above', '+2'], ['Day', '+0.85%', '+0'],
        ['Total', 'Sunny', '+5'], ['Extra', 'row', '+0']] },
  ],
  chart: { type: 'bar', title: 'Sector median change (%)', unit: '%',
    series: [{ label: 'Technology', value: 1.2 }, { label: 'Energy', value: -0.8 }] },
  badge: { kind: 'weather', value: 'sunny', label: 'Sunny', score: 5 },
  links: [
    { title: 'Headline one', url: 'https://news.example.com/1', source: 'Example Wire' },
    { title: 'Bad link', url: 'javascript:alert(1)', source: 'x' },
  ],
  notes: ['Weather describes current conditions.'],
  sources: ['QuantTrade quote cache', 'CBOE VIX quotes'],
  as_of: '2026-11-24T16:15:00-05:00',
  as_of_label: 'Nov 24, 2026 4:15 PM ET',
  automated_label: 'Automated post by Market Weather Bot',
  disclaimer: 'Not investment advice. Signals and observations are generated by fixed rules from market data.',
}

afterEach(cleanup)

describe('BotPostBlock', () => {
  it('always shows the automated label, sources, as-of and disclaimer', () => {
    render(<BotPostBlock payload={payload} compact />)
    expect(screen.getByText('Automated post by Market Weather Bot')).toBeTruthy()
    expect(screen.getByText(/QuantTrade quote cache; CBOE VIX quotes/)).toBeTruthy()
    expect(screen.getByText('Nov 24, 2026 4:15 PM ET')).toBeTruthy()
    expect(screen.getByText(/Not investment advice/)).toBeTruthy()
    expect(screen.getByRole('link', { name: /Methodology/ }).getAttribute('href')).toBe('/community/bots/market_weather')
  })

  it('compact mode truncates tables and hides headline links', () => {
    render(<BotPostBlock payload={payload} compact />)
    expect(screen.getByText('+1 more rows in the full post')).toBeTruthy()
    expect(screen.queryByText('Headline one')).toBeNull()
    expect(screen.queryByText('QQQ +1.20%.')).toBeNull()
  })

  it('full mode renders headlines as title + publisher link, dropping unsafe URLs', () => {
    render(<BotPostBlock payload={payload} />)
    const link = screen.getByText('Headline one').closest('a')!
    expect(link.getAttribute('href')).toBe('https://news.example.com/1')
    expect(link.getAttribute('rel')).toContain('noopener')
    expect(screen.queryByText('Bad link')).toBeNull()
    expect(screen.getByText('Extra')).toBeTruthy()
    expect(screen.getAllByText('Sunny').length).toBeGreaterThan(0)
  })
})

describe('ShowBotsToggle', () => {
  it('reports the toggled value', () => {
    const onChange = vi.fn()
    render(<ShowBotsToggle checked onChange={onChange} />)
    const sw = screen.getByRole('switch', { name: 'Show bot posts' })
    expect(sw.getAttribute('aria-checked')).toBe('true')
    sw.click()
    expect(onChange).toHaveBeenCalledWith(false)
  })
})
