#!/usr/bin/env python3
"""Generate frontend/src/lib/stockPage/universe.ts (the curated /stocks/* list).

Source of truth stays in the backend:
  * backend/app/api/market.py            SP500_STOCKS  (sector -> [(symbol, name)])
  * backend/app/api/forecast.py          _FUNDS        (ETFs we forecast)
  * backend/app/services/ticker_lifecycle.py RETIREMENTS (renamed / acquired / delisted / reused)

Retired and reused tickers are dropped, so the sitemap and the pre-rendered
pages never point at a symbol that stopped trading.

Run from the repo root:  python3 scripts/gen_stock_universe.py
"""
from __future__ import annotations

import ast
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "frontend" / "src" / "lib" / "stockPage" / "universe.ts"

# US share classes that are in the S&P 500 but not in the heatmap sample.
EXTRA_STOCKS = [("Financials", "BRK.B", "Berkshire Hathaway Inc. Class B")]

# Display names for the funds in forecast._FUNDS (the page itself uses the backend name).
ETF_NAMES = {
    "SPY": "SPDR S&P 500 ETF Trust",
    "VOO": "Vanguard S&P 500 ETF",
    "VTI": "Vanguard Total Stock Market ETF",
    "QQQ": "Invesco QQQ Trust",
    "IWM": "iShares Russell 2000 ETF",
    "DIA": "SPDR Dow Jones Industrial Average ETF",
    "XLK": "Technology Select Sector SPDR Fund",
    "XLC": "Communication Services Select Sector SPDR Fund",
    "XLY": "Consumer Discretionary Select Sector SPDR Fund",
    "XLF": "Financial Select Sector SPDR Fund",
    "XLV": "Health Care Select Sector SPDR Fund",
    "XLE": "Energy Select Sector SPDR Fund",
    "XLP": "Consumer Staples Select Sector SPDR Fund",
    "XLI": "Industrial Select Sector SPDR Fund",
    "XLU": "Utilities Select Sector SPDR Fund",
    "XLB": "Materials Select Sector SPDR Fund",
    "XLRE": "Real Estate Select Sector SPDR Fund",
    "GLD": "SPDR Gold Shares",
    "TLT": "iShares 20+ Year Treasury Bond ETF",
}


def _literal(path: Path, name: str):
    tree = ast.parse(path.read_text())
    for node in tree.body:
        if isinstance(node, ast.Assign) and any(getattr(t, "id", None) == name for t in node.targets):
            return ast.literal_eval(node.value)
    raise SystemExit(f"{name} not found in {path}")


def _rows(items: list) -> str:
    return "[\n" + "".join(f"  {json.dumps(i)},\n" for i in items) + "]"


def main() -> int:
    sys.path.insert(0, str(ROOT / "backend"))
    from app.services.ticker_lifecycle import RETIREMENTS  # stdlib-only module

    retired = set(RETIREMENTS)
    sectors = _literal(ROOT / "backend/app/api/market.py", "SP500_STOCKS")
    funds = _literal(ROOT / "backend/app/api/forecast.py", "_FUNDS")

    seen: set[str] = set()
    stocks = []
    rows = [(sector, sym, name) for sector, pairs in sectors.items() for sym, name in pairs] + EXTRA_STOCKS
    for sector, sym, name in rows:
        sym = sym.strip().upper()
        if sym in seen or sym in retired:
            continue
        seen.add(sym)
        stocks.append({"symbol": sym, "name": name, "sector": sector})

    etfs = []
    for sym in ETF_NAMES:
        if sym in funds and sym not in retired and sym not in seen:
            seen.add(sym)
            etfs.append({"symbol": sym, "name": ETF_NAMES[sym], "sector": "ETF"})

    body = [
        "// GENERATED by scripts/gen_stock_universe.py. Do not edit by hand.",
        "// Curated /stocks/* universe: the backend heatmap sample (market.SP500_STOCKS)",
        "// + share classes + the funds the forecast covers, minus every retired or",
        "// reused ticker in app/services/ticker_lifecycle.RETIREMENTS.",
        "",
        "export interface UniverseEntry {",
        "  symbol: string",
        "  name: string",
        "  sector: string",
        "}",
        "",
        f"export const STOCK_UNIVERSE: readonly UniverseEntry[] = {_rows(stocks)}",
        "",
        f"export const ETF_UNIVERSE: readonly UniverseEntry[] = {_rows(etfs)}",
        "",
        f"export const RETIRED_SYMBOLS: readonly string[] = {json.dumps(sorted(retired))}",
        "",
    ]
    OUT.write_text("\n".join(body))
    print(f"wrote {OUT.relative_to(ROOT)}: {len(stocks)} stocks, {len(etfs)} ETFs, {len(retired)} retired")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
